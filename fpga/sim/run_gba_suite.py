#!/usr/bin/env python3
"""Run suite.gba (mGBA test suite) on the Gamebub GBA Verilator sim.

Build the sim first: python3 scripts/build_sim.py gba --build-root build/sim-gba

Each test suite in the ROM's menu is run in its own headless sim process
(in parallel), driven by a generated input script. Per suite, the output
directory gets:

  script.txt      generated sim input script
  log.txt         sim stdout/stderr
  results.txt     the suite's SRAM log (test names + failure details)
  page_NN.png     screenshots of every page of the results list
  video_K_*.png   (Video tests only) actual/expected renders + diff

and a summary table is written to OUT/summary.txt.

Example:
  ./run_gba_suite.py                     # all suites
  ./run_gba_suite.py memory timing       # suites whose names contain these words
  ./run_gba_suite.py 0 2 --out /tmp/res  # by menu index
"""

import argparse
import concurrent.futures
import os
import struct
import subprocess
import sys
import time
from pathlib import Path

FPGA = Path(__file__).resolve().parent.parent
# Defaults assume the mGBA suite checkout sits next to the gamebub repo.
SUITE_DIR = FPGA.parent.parent / "suite"
DEFAULT_SIM = FPGA / "build/sim-gba/VSimGba"
DEFAULT_BIOS = SUITE_DIR / "gba.bios.bin"
DEFAULT_ROM = SUITE_DIR / "suite.gba"

# Menu order, from suites[] in src/main.c.
SUITE_NAMES = [
    "Memory tests",
    "I/O read tests",
    "Timing tests",
    "Timer count-up tests",
    "Timer IRQ tests",
    "Shifter tests",
    "Carry tests",
    "Multiply long tests",
    "BIOS math tests",
    "DMA tests",
    "SIO register R/W tests",
    "SIO timing tests",
    "Misc. edge case tests",
    "Video tests",
]
VIEW_SIZE = 16  # tests per results page (VIEW_SIZE in include/common.h)
IWRAM_BASE = 0x03000000


class Suite:
    def __init__(self, index, name, n_tests, has_run, passes_addr, total_addr):
        self.index = index
        self.name = name
        self.n_tests = n_tests
        self.has_run = has_run
        self.passes_addr = passes_addr
        self.total_addr = total_addr

    @property
    def slug(self):
        s = "".join(c.lower() if c.isalnum() else "_" for c in self.name)
        return f"{self.index:02d}_" + "_".join(p for p in s.split("_") if p)


def read_suites(rom: bytes) -> list[Suite]:
    """Find each `struct TestSuite` in the ROM via the pointer to its name."""
    suites = []
    for index, name in enumerate(SUITE_NAMES):
        off = rom.find(name.encode() + b"\0")
        if off < 0:
            sys.exit(f"ERROR: suite name {name!r} not found in ROM")
        ptr = struct.pack("<I", 0x08000000 + off)
        pos = rom.find(ptr)
        while pos >= 0 and pos % 4:
            pos = rom.find(ptr, pos + 1)
        if pos < 0:
            sys.exit(f"ERROR: TestSuite struct for {name!r} not found in ROM")
        # name, run, list, show, nTests, passes*, totalResults*
        _, run, _, _, n_tests, passes, total = struct.unpack("<7I", rom[pos : pos + 28])
        suites.append(Suite(index, name, n_tests, run != 0, passes, total))
    return suites


def make_script(suite: Suite, boot_frames: int, settle_frames: int) -> str:
    lines = [
        f"# Generated by run_suite.py for: {suite.name}",
        f"wait {boot_frames}  # BIOS intro -> suite menu",
    ]
    if suite.index:
        lines.append(f"press DOWN {suite.index}")
    lines.append("press A")

    if suite.has_run:
        lines += [
            f"wait {settle_frames}  # let the suite run",
            "dump iwram iwram.bin",
            "sav results.sav",
            "screenshot page_00.png",
        ]
        # Paging: the first RIGHT moves the cursor to the bottom of the view,
        # each following RIGHT scrolls one page (the last page is clamped).
        pages = (suite.n_tests + VIEW_SIZE - 1) // VIEW_SIZE
        for page in range(1, pages):
            lines.append("press RIGHT 2" if page == 1 else "press RIGHT")
            lines.append(f"screenshot page_{page:02d}.png")
    else:
        # Video tests: open each test, capture the actual and expected render
        # with the nav label hidden (START), then return to the list.
        lines.append("wait 30")
        lines.append("screenshot page_00.png")
        for k in range(suite.n_tests):
            if k:
                lines.append("press DOWN")
            lines += [
                "press A",
                "wait 20",
                "press START  # hide nav label",
                "wait 30",
                f"screenshot video_{k}_actual.png",
                "press RIGHT",
                "wait 30",
                f"screenshot video_{k}_expected.png",
                "press B",
                "wait 20",
            ]
    lines.append("quit")
    return "\n".join(lines) + "\n"


def read_u32(mem: bytes, addr: int):
    off = addr - IWRAM_BASE
    if 0 <= off <= len(mem) - 4:
        return struct.unpack_from("<I", mem, off)[0]
    return None


def read_sav_text(path: Path) -> str:
    data = path.read_bytes() if path.exists() else b""
    end = data.find(b"\0")
    if end >= 0:
        data = data[:end]
    return data.decode("ascii", "replace")


def compare_video(out_dir: Path, k: int):
    try:
        from PIL import Image, ImageChops
    except ImportError:
        return "no PIL"
    a = Image.open(out_dir / f"video_{k}_actual.png").convert("RGB")
    e = Image.open(out_dir / f"video_{k}_expected.png").convert("RGB")
    diff = ImageChops.difference(a, e)
    bbox = diff.getbbox()
    if bbox is None:
        return "match"
    mask = diff.convert("L").point(lambda v: 255 if v else 0)
    n = mask.histogram()[255]
    mask.save(out_dir / f"video_{k}_diff.png")
    return f"MISMATCH ({n} px)"


def run_one(suite: Suite, args) -> dict:
    out_dir = args.out / suite.slug
    out_dir.mkdir(parents=True, exist_ok=True)
    for old in out_dir.glob("*.png"):
        old.unlink()
    # Private ROM symlink so the sim's auto-saved .sav lands here, not next
    # to the shared ROM (and parallel runs don't clobber each other).
    rom_link = out_dir / "suite.gba"
    if rom_link.is_symlink() or rom_link.exists():
        rom_link.unlink()
    rom_link.symlink_to(args.rom.resolve())
    (out_dir / "suite.sav").unlink(missing_ok=True)

    script = out_dir / "script.txt"
    script.write_text(make_script(suite, args.boot_frames, args.settle_frames))

    start = time.time()
    with open(out_dir / "log.txt", "w") as log:
        proc = subprocess.run(
            [str(args.sim), "--bios-path", str(args.bios), "--headless",
             "--script", str(script), str(rom_link)],
            stdout=log, stderr=subprocess.STDOUT,
        )
    result = {"suite": suite, "dir": out_dir, "rc": proc.returncode,
              "seconds": time.time() - start}

    if suite.has_run:
        text = read_sav_text(out_dir / "results.sav")
        (out_dir / "results.txt").write_text(text)
        result["fail_lines"] = sum(1 for l in text.splitlines() if l.endswith("FAIL"))
        iwram_path = out_dir / "iwram.bin"
        if iwram_path.exists():
            mem = iwram_path.read_bytes()
            result["passes"] = read_u32(mem, suite.passes_addr)
            result["total"] = read_u32(mem, suite.total_addr)
    else:
        result["video"] = [compare_video(out_dir, k) for k in range(suite.n_tests)]
    return result


def select_suites(suites, selectors):
    if not selectors:
        return suites
    chosen = []
    for sel in selectors:
        if sel.isdigit():
            matches = [suites[int(sel)]]
        else:
            matches = [s for s in suites if sel.lower() in s.name.lower()]
        if not matches:
            sys.exit(f"ERROR: no suite matches {sel!r}")
        chosen += [m for m in matches if m not in chosen]
    return chosen


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("suites", nargs="*", help="menu index or name substring (default: all)")
    parser.add_argument("--sim", type=Path, default=DEFAULT_SIM)
    parser.add_argument("--bios", type=Path, default=DEFAULT_BIOS)
    parser.add_argument("--rom", type=Path, default=DEFAULT_ROM)
    parser.add_argument("--out", type=Path, default=FPGA / "build/suite-results")
    parser.add_argument("-j", "--jobs", type=int, default=os.cpu_count())
    parser.add_argument("--boot-frames", type=int, default=330,
                        help="frames until the suite menu is up (official BIOS intro ends ~frame 270)")
    parser.add_argument("--settle-frames", type=int, default=300,
                        help="frames to wait after starting a suite (all finish in <200 today)")
    parser.add_argument("--list", action="store_true", help="list suites and exit")
    args = parser.parse_args()

    suites = read_suites(args.rom.read_bytes())
    if args.list:
        for s in suites:
            print(f"{s.index:2d}  {s.name:24s} {s.n_tests:4d} tests")
        return

    chosen = select_suites(suites, args.suites)
    args.out.mkdir(parents=True, exist_ok=True)
    print(f"Running {len(chosen)} suite(s) with {args.jobs} jobs -> {args.out}")

    results = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=args.jobs) as pool:
        futures = [pool.submit(run_one, s, args) for s in chosen]
        for fut in concurrent.futures.as_completed(futures):
            r = fut.result()
            print(f"  done: {r['suite'].name} ({r['seconds']:.0f}s, rc={r['rc']})")
            results.append(r)
    results.sort(key=lambda r: r["suite"].index)

    lines = [f"{'Suite':24s} {'Passed':>13s}  Notes"]
    for r in results:
        s = r["suite"]
        if s.has_run:
            p, t = r.get("passes"), r.get("total")
            score = f"{p}/{t}" if p is not None else "?"
            note = f"{r['fail_lines']} FAIL lines in results.txt"
        else:
            ok = sum(1 for v in r["video"] if v == "match")
            score = f"{ok}/{len(r['video'])}"
            note = "actual vs expected screenshots: " + ", ".join(
                f"{k}:{v}" for k, v in enumerate(r["video"]))
        if r["rc"]:
            note += f"  [sim exit code {r['rc']}]"
        lines.append(f"{s.name:24s} {score:>13s}  {note}")
    summary = "\n".join(lines) + "\n"
    (args.out / "summary.txt").write_text(summary)
    print()
    print(summary, end="")


if __name__ == "__main__":
    main()
